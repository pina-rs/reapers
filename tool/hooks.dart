/// Guards `main` against changes the checks have not passed.
///
/// There are no pull requests in this repository. A branch reaches `main` by
/// being merged locally, and this is what makes that safe: `main` can only
/// move to a commit that `dart tool/merge.dart` has just checked.
///
/// Git cannot block a fast-forward merge with an ordinary hook:
/// `pre-merge-commit` does not run for fast-forwards and `post-merge` runs
/// after the fact. The one hook that runs before any ref moves, a
/// fast-forward into `main` included, is `reference-transaction`, and it can
/// abort the transaction. That is the hook this installs.
///
///     dart tool/hooks.dart install     write the hooks and point git at them
///     dart tool/hooks.dart status      report whether main is guarded
///     dart tool/hooks.dart uninstall   remove the hooks and the git config
///
/// What the hooks do:
/// - `main` may only move to a commit that has a verification record, which
///   `tool/merge.dart` writes after the checks pass on exactly that commit.
///   A direct commit, a reset, a pull or a hand-run `git merge` is refused.
/// - `git commit` on `main` is refused before it happens, so the message is
///   about the commit rather than about a ref.
/// - Every other branch, every tag and git's own internal refs are untouched.
/// - `REAPERS_SKIP_HOOKS=1` bypasses both, for deliberate recovery work.
///
/// Hooks are local to a clone. Run `install` once after cloning.
library;

import 'dart:io';

/// Where verification records are kept, under the shared git directory so
/// every worktree of the repository sees the same ones.
const verifiedDirectory = 'local-ci/verified';

/// The script installed as the `reference-transaction` hook.
///
/// It is POSIX shell so it costs nothing to start: git calls this hook for
/// every ref update there is.
const referenceTransactionHook = r'''#!/bin/sh
# Generated by tool/hooks.dart. Edit that file, then re-run:
#   dart tool/hooks.dart install
#
# Runs before any ref is updated. Exiting non-zero aborts the update.

# Only the prepared phase can veto; committed and aborted are notifications.
[ "$1" = "prepared" ] || exit 0

[ -n "$REAPERS_SKIP_HOOKS" ] && exit 0

repo_root=$(git rev-parse --show-toplevel 2>/dev/null) || exit 0

while read -r old new ref; do
  [ "$ref" = "refs/heads/main" ] || continue

  git_dir=$(git rev-parse --git-common-dir 2>/dev/null) || exit 1
  case "$git_dir" in
    /*) ;;
    *) git_dir="$repo_root/$git_dir" ;;
  esac

  case "$new" in
    0000000000000000000000000000000000000000)
      # Packing refs deletes the loose copy after writing an identical packed
      # one. That is storage, not a deletion: allow it only when the packed
      # copy already holds the same commit and nothing is rewriting it.
      if [ "$old" != "0000000000000000000000000000000000000000" ] &&
         [ ! -e "$git_dir/packed-refs.lock" ] &&
         [ "$(awk '$2 == "refs/heads/main" { print $1 }' "$git_dir/packed-refs" 2>/dev/null)" = "$old" ]; then
        continue
      fi

      echo "reapers: refusing to delete main." >&2
      exit 1
      ;;
  esac

  # A rewrite that does not move the commit needs no verification.
  [ "$old" = "$new" ] && continue
  [ "$(git rev-parse --verify "$ref" 2>/dev/null)" = "$new" ] && continue

  verified=no
  for record in "$git_dir"/local-ci/verified/*.json; do
    [ -f "$record" ] || continue
    # Match the commit without needing jq.
    case "$(cat "$record")" in
      *"$new"*) verified=yes ;;
    esac
    [ "$verified" = "yes" ] && break
  done

  if [ "$verified" = "no" ]; then
    cat >&2 <<MESSAGE
reapers: refusing to move main to $new.

That commit has not passed the checks. From the branch that holds it, run:

    dart tool/merge.dart

which runs every check and, if they pass, fast-forwards main to it.

Set REAPERS_SKIP_HOOKS=1 to bypass for deliberate recovery work.
MESSAGE
    exit 1
  fi
done

exit 0
''';

/// The script installed as the `pre-commit` hook.
///
/// `reference-transaction` already refuses this, but failing at commit time
/// says what the person was actually doing.
const preCommitHook = r'''#!/bin/sh
# Generated by tool/hooks.dart. Edit that file, then re-run:
#   dart tool/hooks.dart install

[ -n "$REAPERS_SKIP_HOOKS" ] && exit 0

branch=$(git symbolic-ref --short HEAD 2>/dev/null) || exit 0
[ "$branch" = "main" ] || exit 0

cat >&2 <<'MESSAGE'
reapers: refusing to commit directly on main.

Work on a branch, then merge it through the checks:

    git switch -c feat/your-change
    dart tool/merge.dart

Set REAPERS_SKIP_HOOKS=1 to bypass for deliberate recovery work.
MESSAGE
exit 1
''';

const _hooks = {
  'reference-transaction': referenceTransactionHook,
  'pre-commit': preCommitHook,
};

void main(List<String> arguments) {
  switch (arguments.firstOrNull ?? 'status') {
    case 'install':
      install();
    case 'uninstall':
      uninstall();
    case 'status':
      exit(status() ? 0 : 1);
    case 'help' || '--help' || '-h':
      _usage();
    case final unknown:
      stderr.writeln('Unknown command "$unknown".\n');
      _usage();
      exit(64);
  }
}

/// Writes the hooks and points git at them.
///
/// `core.hooksPath` is set to an absolute path inside the shared git
/// directory. A relative one would be resolved against each worktree and
/// silently find nothing there.
void install() {
  final directory = Directory('${commonGitDirectory()}/local-ci/hooks')
    ..createSync(recursive: true);

  for (final MapEntry(key: name, value: script) in _hooks.entries) {
    final file = File('${directory.path}/$name')..writeAsStringSync(script);
    // dart:io has no chmod, and a hook git cannot execute is worse than no
    // hook: it is skipped without a word.
    final chmod = Process.runSync('chmod', ['+x', file.path]);

    if (chmod.exitCode != 0) {
      stderr.writeln('Could not make ${file.path} executable.');
      exit(1);
    }
  }

  _git(['config', 'core.hooksPath', directory.path]);
  stdout.writeln(
    'main is guarded. Hooks are in ${directory.path}, and every worktree of '
    'this repository uses them.',
  );
}

void uninstall() {
  final configured = _hooksPath();

  if (configured == null) {
    stdout.writeln('No core.hooksPath is set; nothing to remove.');

    return;
  }

  _git(['config', '--unset', 'core.hooksPath']);

  final directory = Directory(configured);

  if (directory.existsSync()) {
    directory.deleteSync(recursive: true);
  }

  stdout.writeln('Removed core.hooksPath and $configured. main is unguarded.');
}

/// Prints whether `main` is guarded and returns whether it is.
bool status() {
  final configured = _hooksPath();

  if (configured == null) {
    stdout.writeln(
      'main is NOT guarded. Install the hooks with:\n'
      '    dart tool/hooks.dart install',
    );

    return false;
  }

  var current = true;

  stdout.writeln('core.hooksPath: $configured');

  for (final MapEntry(key: name, value: script) in _hooks.entries) {
    final file = File('$configured/$name');
    final state = switch (file) {
      _ when !file.existsSync() => 'missing',
      _ when file.readAsStringSync() != script => 'stale, re-run install',
      _ => 'installed',
    };

    current = current && state == 'installed';
    stdout.writeln('  ${name.padRight(22)} $state');
  }

  return current;
}

/// The git directory shared by every worktree of this repository.
String commonGitDirectory() {
  final result = Process.runSync('git', ['rev-parse', '--git-common-dir']);

  if (result.exitCode != 0) {
    stderr.writeln('Not inside a git repository.');
    exit(1);
  }

  final raw = (result.stdout as String).trim();

  return File(raw).isAbsolute ? raw : File(raw).absolute.path;
}

String? _hooksPath() {
  final result = Process.runSync('git', ['config', '--get', 'core.hooksPath']);
  final configured = (result.stdout as String).trim();

  return configured.isEmpty ? null : configured;
}

void _git(List<String> arguments) {
  final result = Process.runSync('git', arguments);

  if (result.exitCode != 0) {
    stderr.writeln('git ${arguments.join(' ')} failed:\n${result.stderr}');
    exit(1);
  }
}

void _usage() {
  stdout.writeln('''
Guard main against changes the checks have not passed.

  dart tool/hooks.dart install     write the hooks and point git at them
  dart tool/hooks.dart status      report whether main is guarded
  dart tool/hooks.dart uninstall   remove the hooks and the git config

Bypass a refused operation with REAPERS_SKIP_HOOKS=1.''');
}
