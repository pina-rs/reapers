//! The Reapers landing page, on leptoskit: what the game is, how a hunt
//! plays, who you are in it and what you hunt, and a way into it.
//!
//! It is the `landing` application of the repository's
//! `leptoskit.workspace.toml`, a separate frontend from the game. It renders
//! in the browser and `leptoskit build` makes a static site of it. Every
//! string it shows is in `locales/en.arb`.

pub mod config;
#[allow(
	clippy::all,
	clippy::pedantic,
	reason = "generated by `leptoskit l10n`"
)]
pub mod l10n;
pub mod page;
#[allow(
	clippy::all,
	clippy::pedantic,
	reason = "generated by `leptoskit plugin:router routes`"
)]
pub mod routes;

/// The page in the browser: the strings for the reader's languages, and the
/// route the address bar names.
#[cfg(all(target_arch = "wasm32", feature = "web"))]
#[leptos::component]
pub fn Landing() -> impl leptos::prelude::IntoView {
	use routes::Navigation;
	use routes::Route;

	l10n::L10n::new(&leptoskit_l10n::browser_locales()).provide();
	let navigation = Navigation::from_browser().unwrap_or_else(|_| Navigation::new(Route::Index));
	move || leptoskit::web::render(navigation.render())
}

/// Mounts the page when the browser loads its Wasm module.
#[cfg(all(target_arch = "wasm32", feature = "web"))]
#[wasm_bindgen::prelude::wasm_bindgen(start)]
pub fn start() {
	console_error_panic_hook::set_once();
	#[cfg(feature = "devtools")]
	leptoskit::devtools::install(env!("CARGO_PKG_NAME"));
	leptos::mount::mount_to_body(Landing);
}
