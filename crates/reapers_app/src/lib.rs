/// The browser adapter for the same tree.
#[cfg(all(target_arch = "wasm32", feature = "web"))]
#[leptos::component]
pub fn App() -> impl leptos::prelude::IntoView {
	let navigation = app::navigation();
	app::start(navigation.clone());
	move || leptoskit::web::render(app::screen(&navigation))
}

/// Mounts the game when the browser loads its Wasm module.
#[cfg(all(target_arch = "wasm32", feature = "web"))]
#[wasm_bindgen::prelude::wasm_bindgen(start)]
pub fn start() {
	console_error_panic_hook::set_once();
	#[cfg(feature = "devtools")]
	leptoskit::devtools::install(env!("CARGO_PKG_NAME"));
	leptos::mount::mount_to_body(App);
}

