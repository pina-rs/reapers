//! Guards `main` against changes the checks have not passed.
//!
//! There are no pull requests in this repository. A branch reaches `main` by
//! being merged locally, and this is what makes that safe: `main` can only
//! move to a commit that `cargo xtask merge` has just checked.
//!
//! Git cannot block a fast-forward merge with an ordinary hook:
//! `pre-merge-commit` does not run for fast-forwards and `post-merge` runs
//! after the fact. The one hook that runs before any ref moves, a
//! fast-forward into `main` included, is `reference-transaction`, and it can
//! abort the transaction. That is the hook this installs.
//!
//! ```sh
//! cargo xtask hooks install     # write the hooks and point git at them
//! cargo xtask hooks status      # report whether main is guarded
//! cargo xtask hooks uninstall   # remove the hooks and the git config
//! ```
//!
//! What the hooks do:
//! - `main` may only move to a commit that has a verification record, which
//!   `cargo xtask merge` writes after the checks pass on exactly that
//!   commit. A direct commit, a reset, a pull or a hand-run `git merge` is
//!   refused.
//! - `git commit` on `main` is refused before it happens, so the message is
//!   about the commit rather than about a ref.
//! - Every other branch, every tag and git's own internal refs are untouched.
//! - `REAPERS_SKIP_HOOKS=1` bypasses both, for deliberate recovery work.
//!
//! Hooks are local to a clone. Run `install` once after cloning.

use std::fs;
use std::path::Path;
use std::path::PathBuf;

use clap::Subcommand;

use crate::git::Git;
use crate::run::Failure;
use crate::run::Outcome;

/// Where verification records are kept, under the shared git directory so
/// every worktree of the repository sees the same ones.
pub const VERIFIED_DIRECTORY: &str = "local-ci/verified";

/// The script installed as the `reference-transaction` hook.
///
/// It is POSIX shell so it costs nothing to start: git calls this hook for
/// every ref update there is.
pub const REFERENCE_TRANSACTION_HOOK: &str = r#"#!/bin/sh
# Generated by crates/xtask/src/hooks.rs. Edit that file, then re-run:
#   cargo xtask hooks install
#
# Runs before any ref is updated. Exiting non-zero aborts the update.

# Only the prepared phase can veto; committed and aborted are notifications.
[ "$1" = "prepared" ] || exit 0

[ -n "$REAPERS_SKIP_HOOKS" ] && exit 0

repo_root=$(git rev-parse --show-toplevel 2>/dev/null) || exit 0

while read -r old new ref; do
  [ "$ref" = "refs/heads/main" ] || continue

  git_dir=$(git rev-parse --git-common-dir 2>/dev/null) || exit 1
  case "$git_dir" in
    /*) ;;
    *) git_dir="$repo_root/$git_dir" ;;
  esac

  case "$new" in
    0000000000000000000000000000000000000000)
      # Packing refs deletes the loose copy after writing an identical packed
      # one. That is storage, not a deletion: allow it only when the packed
      # copy already holds the same commit and nothing is rewriting it.
      if [ "$old" != "0000000000000000000000000000000000000000" ] &&
         [ ! -e "$git_dir/packed-refs.lock" ] &&
         [ "$(awk '$2 == "refs/heads/main" { print $1 }' "$git_dir/packed-refs" 2>/dev/null)" = "$old" ]; then
        continue
      fi

      echo "reapers: refusing to delete main." >&2
      exit 1
      ;;
  esac

  # A rewrite that does not move the commit needs no verification.
  [ "$old" = "$new" ] && continue
  [ "$(git rev-parse --verify "$ref" 2>/dev/null)" = "$new" ] && continue

  verified=no
  for record in "$git_dir"/local-ci/verified/*.json; do
    [ -f "$record" ] || continue
    # Match the commit without needing jq.
    case "$(cat "$record")" in
      *"$new"*) verified=yes ;;
    esac
    [ "$verified" = "yes" ] && break
  done

  if [ "$verified" = "no" ]; then
    cat >&2 <<MESSAGE
reapers: refusing to move main to $new.

That commit has not passed the checks. From the branch that holds it, run:

    cargo xtask merge

which runs every check and, if they pass, fast-forwards main to it.

Set REAPERS_SKIP_HOOKS=1 to bypass for deliberate recovery work.
MESSAGE
    exit 1
  fi
done

exit 0
"#;

/// The script installed as the `pre-commit` hook.
///
/// `reference-transaction` already refuses this, but failing at commit time
/// says what the person was actually doing.
pub const PRE_COMMIT_HOOK: &str = r#"#!/bin/sh
# Generated by crates/xtask/src/hooks.rs. Edit that file, then re-run:
#   cargo xtask hooks install

[ -n "$REAPERS_SKIP_HOOKS" ] && exit 0

branch=$(git symbolic-ref --short HEAD 2>/dev/null) || exit 0
[ "$branch" = "main" ] || exit 0

cat >&2 <<'MESSAGE'
reapers: refusing to commit directly on main.

Work on a branch, then merge it through the checks:

    git switch -c feat/your-change
    cargo xtask merge

Set REAPERS_SKIP_HOOKS=1 to bypass for deliberate recovery work.
MESSAGE
exit 1
"#;

const HOOKS: [(&str, &str); 2] = [
	("reference-transaction", REFERENCE_TRANSACTION_HOOK),
	("pre-commit", PRE_COMMIT_HOOK),
];

#[derive(Clone, Copy, Default, Subcommand)]
pub enum Action {
	/// Write the hooks and point git at them.
	Install,
	/// Report whether main is guarded; exits non-zero when it is not.
	#[default]
	Status,
	/// Remove the hooks and the git config.
	Uninstall,
}

pub fn main(git: &Git, action: Action) -> Outcome {
	match action {
		Action::Install => {
			install(git).map(|directory| {
				println!(
					"main is guarded. Hooks are in {}, and every worktree of this repository uses them.",
					directory.display()
				);
			})
		}
		Action::Uninstall => uninstall(git),
		Action::Status => {
			if status(git) {
				Ok(())
			} else {
				Err(Failure::new(""))
			}
		}
	}
}

/// Writes the hooks and points git at them, and returns where they are.
///
/// `core.hooksPath` is set to an absolute path inside the shared git
/// directory. A relative one would be resolved against each worktree and
/// silently find nothing there.
pub fn install(git: &Git) -> Outcome<PathBuf> {
	let directory = git.common_directory()?.join("local-ci/hooks");

	fs::create_dir_all(&directory)?;

	for (name, script) in HOOKS {
		let file = directory.join(name);

		fs::write(&file, script)?;
		// A hook git cannot execute is worse than no hook: it is skipped
		// without a word.
		make_executable(&file)?;
	}

	let path = directory
		.to_str()
		.ok_or_else(|| Failure::new("The git directory's path is not UTF-8."))?;

	git.read(&["config", "core.hooksPath", path])?;

	Ok(directory)
}

#[cfg(unix)]
fn make_executable(file: &Path) -> Outcome {
	use std::os::unix::fs::PermissionsExt;

	fs::set_permissions(file, fs::Permissions::from_mode(0o755)).map_err(|error| {
		Failure::new(format!(
			"Could not make {} executable: {error}.",
			file.display()
		))
	})
}

#[cfg(not(unix))]
fn make_executable(_: &Path) -> Outcome {
	Err(Failure::new(
		"The hooks are POSIX shell, and need a Unix to run.",
	))
}

pub fn uninstall(git: &Git) -> Outcome {
	let Some(configured) = hooks_path(git) else {
		println!("No core.hooksPath is set; nothing to remove.");

		return Ok(());
	};

	git.read(&["config", "--unset", "core.hooksPath"])?;

	if configured.is_dir() {
		fs::remove_dir_all(&configured)?;
	}

	println!(
		"Removed core.hooksPath and {}. main is unguarded.",
		configured.display()
	);

	Ok(())
}

/// Prints whether `main` is guarded and returns whether it is: every hook
/// where git looks for it, exactly as this tool writes it.
pub fn status(git: &Git) -> bool {
	let Some(configured) = hooks_path(git) else {
		println!("main is NOT guarded. Install the hooks with:\n    cargo xtask hooks install");

		return false;
	};

	let mut current = true;

	println!("core.hooksPath: {}", configured.display());

	for (name, script) in HOOKS {
		let state = match fs::read_to_string(configured.join(name)) {
			Err(_) => "missing",
			Ok(installed) if installed != script => "stale, re-run install",
			Ok(_) => "installed",
		};

		current = current && state == "installed";
		println!("  {name:<22} {state}");
	}

	current
}

fn hooks_path(git: &Git) -> Option<PathBuf> {
	let configured = git.read(&["config", "--get", "core.hooksPath"]).ok()?;

	(!configured.is_empty()).then(|| PathBuf::from(configured))
}

#[cfg(test)]
pub mod tests {
	use std::sync::atomic::AtomicUsize;
	use std::sync::atomic::Ordering;

	use super::*;

	/// A git repository of its own in the temporary directory, deleted when
	/// dropped, with one commit on `main`.
	pub struct Scratch {
		pub git: Git,
	}

	impl Scratch {
		pub fn new() -> Self {
			static NEXT: AtomicUsize = AtomicUsize::new(0);

			let directory = std::env::temp_dir().join(format!(
				"reapers-xtask-{}-{}",
				std::process::id(),
				NEXT.fetch_add(1, Ordering::Relaxed)
			));

			if directory.exists() {
				fs::remove_dir_all(&directory).unwrap();
			}
			fs::create_dir_all(&directory).unwrap();

			let git = Git::isolated(&directory);

			git.read(&["init", "--quiet", "--initial-branch=main"])
				.unwrap();
			let scratch = Self { git };
			scratch.commit("first");

			scratch
		}

		pub fn path(&self) -> &Path {
			self.git.directory()
		}

		/// Writes a file named after `message` and commits it.
		pub fn commit(&self, message: &str) -> String {
			fs::write(self.path().join(format!("{message}.txt")), message).unwrap();
			self.git.read(&["add", "--all"]).unwrap();
			self.git
				.read(&["commit", "--quiet", "--message", message])
				.unwrap();
			self.git.read(&["rev-parse", "HEAD"]).unwrap()
		}

		/// Writes a verification record for `commit`, as the merge does.
		pub fn verify(&self, commit: &str) {
			let directory = self
				.git
				.common_directory()
				.unwrap()
				.join(VERIFIED_DIRECTORY);

			fs::create_dir_all(&directory).unwrap();
			fs::write(
				directory.join("test.json"),
				format!("{{\"commit\": \"{commit}\"}}\n"),
			)
			.unwrap();
		}

		pub fn head_of(&self, branch: &str) -> String {
			self.git.read(&["rev-parse", branch]).unwrap()
		}
	}

	impl Drop for Scratch {
		fn drop(&mut self) {
			let _ = fs::remove_dir_all(self.path());
		}
	}

	fn guarded() -> Scratch {
		let scratch = Scratch::new();

		install(&scratch.git).unwrap();
		scratch
	}

	fn stderr(output: &std::process::Output) -> String {
		String::from_utf8_lossy(&output.stderr).into_owned()
	}

	#[test]
	fn install_reports_guarded_and_uninstall_unguarded() {
		let scratch = Scratch::new();

		assert!(!status(&scratch.git));
		let directory = install(&scratch.git).unwrap();
		assert!(status(&scratch.git));

		// A hook edited by hand no longer counts as the guard.
		fs::write(directory.join("pre-commit"), "#!/bin/sh\nexit 0\n").unwrap();
		assert!(!status(&scratch.git));

		install(&scratch.git).unwrap();
		uninstall(&scratch.git).unwrap();
		assert!(!status(&scratch.git));
		assert!(!directory.exists());
	}

	#[test]
	fn refuses_a_commit_on_main() {
		let scratch = guarded();
		let before = scratch.head_of("main");

		fs::write(scratch.path().join("direct.txt"), "direct").unwrap();
		scratch.git.read(&["add", "--all"]).unwrap();
		let output = scratch
			.git
			.output(&["commit", "--message", "direct"])
			.unwrap();

		assert!(!output.status.success());
		assert!(stderr(&output).contains("refusing to commit directly on main"));
		assert_eq!(scratch.head_of("main"), before);
	}

	#[test]
	fn refuses_to_move_main_to_an_unchecked_commit() {
		let scratch = guarded();
		let before = scratch.head_of("main");

		scratch
			.git
			.read(&["switch", "--quiet", "--create", "feat/thing"])
			.unwrap();
		let feature = scratch.commit("feature");

		for attempt in [
			vec!["fetch", "--quiet", ".", "feat/thing:main"],
			vec!["update-ref", "refs/heads/main", feature.as_str()],
			vec!["branch", "--force", "main", "feat/thing"],
		] {
			let output = scratch.git.output(&attempt).unwrap();

			assert!(!output.status.success(), "{attempt:?} moved main");
			assert!(stderr(&output).contains("has not passed the checks"));
			assert_eq!(scratch.head_of("main"), before);
		}

		// Other branches move freely.
		scratch.commit("more");
		scratch
			.git
			.read(&["branch", "--force", "other", "main"])
			.unwrap();
	}

	#[test]
	fn lets_main_move_to_a_checked_commit() {
		let scratch = guarded();

		scratch
			.git
			.read(&["switch", "--quiet", "--create", "feat/thing"])
			.unwrap();
		let feature = scratch.commit("feature");
		scratch.verify(&feature);
		scratch
			.git
			.read(&["fetch", "--quiet", ".", "feat/thing:main"])
			.unwrap();

		assert_eq!(scratch.head_of("main"), feature);
	}

	#[test]
	fn refuses_to_delete_main_but_lets_refs_be_packed() {
		let scratch = guarded();

		scratch
			.git
			.read(&["switch", "--quiet", "--create", "feat/thing"])
			.unwrap();
		let output = scratch
			.git
			.output(&["branch", "--delete", "--force", "main"])
			.unwrap();
		assert!(!output.status.success());
		assert!(stderr(&output).contains("refusing to delete main"));

		let before = scratch.head_of("main");
		scratch.git.read(&["pack-refs", "--all"]).unwrap();
		assert_eq!(scratch.head_of("main"), before);
	}

	#[test]
	fn the_bypass_is_honoured() {
		let scratch = guarded();

		scratch
			.git
			.read(&["switch", "--quiet", "--create", "feat/thing"])
			.unwrap();
		let feature = scratch.commit("feature");
		let output = scratch
			.git
			.command(&["fetch", "--quiet", ".", "feat/thing:main"])
			.env("REAPERS_SKIP_HOOKS", "1")
			.output()
			.unwrap();

		assert!(output.status.success(), "{}", stderr(&output));
		assert_eq!(scratch.head_of("main"), feature);
	}
}
